/**
 * calculix_case_generator.js
 *
 * CalculiX FEA input deck (.inp) generator: *NODE, *ELEMENT (C3D8/C3D20),
 * *MATERIAL with *ELASTIC and optional *PLASTIC, *STEP/*STATIC, *BOUNDARY
 * and *CLOAD referencing declared node sets. Pure deterministic text
 * generation, no external dependencies.
 */

'use strict';

const VALID_ELEMENT_TYPES = new Set(['C3D8', 'C3D20', 'C3D8R']);

class CalculixCaseGenerator {
  /**
   * Generates a complete CalculiX .inp file.
   *
   *   nodes:             array of [id, x, y, z]
   *   elements:          array of connectivity arrays ([id, n1, ..., n8])
   *   nodeSets:          { name: [nodeId, ...] }
   *   boundaryConditions: array of [setLabel, dofStart, dofEnd, value]
   *                       or { set, dofs: [dofStart, dofEnd], value }
   *   appliedLoads:      array of [nodeId, dof, magnitude]
   *                       or { set, dof, magnitude }
   */
  static generateInputDeck({
    heading = 'CalculiX Structural Analysis',
    nodes = [],
    elements = [],
    elementType = 'C3D8',
    materialName = 'STEEL',
    youngsModulus_MPa = 200000,
    poissonsRatio = 0.3,
    yieldStress_MPa = null,
    hardeningStrain = 0.15,
    density_kg_m3 = null,
    nodeSets = {},
    boundaryConditions = [],
    appliedLoads = [],
    isNonLinearGeom = false,
    stepType = 'STATIC'
  } = {}) {
    if (!VALID_ELEMENT_TYPES.has(elementType)) {
      throw new Error(
        `Invalid CalculiX element type "${elementType}"; expected one of ${[...VALID_ELEMENT_TYPES].join(', ')}`
      );
    }
    if (youngsModulus_MPa === undefined || youngsModulus_MPa === null || !(youngsModulus_MPa > 0)) {
      throw new Error(`youngsModulus_MPa is required and must be positive, got ${JSON.stringify(youngsModulus_MPa)}`);
    }
    if (poissonsRatio === undefined || poissonsRatio === null || poissonsRatio <= -1 || poissonsRatio >= 0.5) {
      throw new Error(`poissonsRatio must satisfy -1 < nu < 0.5, got ${JSON.stringify(poissonsRatio)}`);
    }
    if (!Array.isArray(nodes) || nodes.length === 0) {
      throw new Error('nodes must be a non-empty array of [id, x, y, z]');
    }
    if (!Array.isArray(elements) || elements.length === 0) {
      throw new Error('elements must be a non-empty array of connectivity lists');
    }
    for (const n of nodes) {
      if (!Array.isArray(n) || n.length !== 4 || n.some((v) => typeof v !== 'number')) {
        throw new Error(`Invalid node entry ${JSON.stringify(n)}; expected [id, x, y, z]`);
      }
    }

    const nodeIdSet = new Set(nodes.map((n) => n[0]));
    for (const [name, ids] of Object.entries(nodeSets)) {
      if (!Array.isArray(ids) || ids.length === 0) {
        throw new Error(`nodeSets["${name}"] must be a non-empty array of node ids`);
      }
      for (const id of ids) {
        if (!nodeIdSet.has(id)) {
          throw new Error(`nodeSets["${name}"] references unknown node ${id}`);
        }
      }
    }

    const lines = [
      '*HEADING',
      heading,
      '** Generated by OmniEng Engineering Engine',
      '** Units: mm, N, MPa, s',
      '*NODE'
    ];

    for (const n of nodes) {
      lines.push(`${n[0]}, ${n[1]}, ${n[2]}, ${n[3]}`);
    }

    lines.push(`*ELEMENT, TYPE=${elementType}, ELSET=EBODY`);
    for (const e of elements) {
      lines.push(e.join(', '));
    }

    lines.push(
      `*SOLID SECTION, ELSET=EBODY, MATERIAL=${materialName}`,
      `*MATERIAL, NAME=${materialName}`,
      '*ELASTIC',
      `${youngsModulus_MPa}, ${poissonsRatio}`
    );

    if (density_kg_m3 !== null && density_kg_m3 !== undefined) {
      if (!(density_kg_m3 > 0)) {
        throw new Error(`density_kg_m3 must be positive when provided, got ${JSON.stringify(density_kg_m3)}`);
      }
      lines.push('*DENSITY', `${density_kg_m3}`);
    }

    if (yieldStress_MPa !== null && yieldStress_MPa !== undefined) {
      if (!(yieldStress_MPa > 0)) {
        throw new Error(`yieldStress_MPa must be positive when provided, got ${JSON.stringify(yieldStress_MPa)}`);
      }
      lines.push('*PLASTIC', `${yieldStress_MPa}, 0.0`, `${yieldStress_MPa * 1.5}, ${hardeningStrain}`);
    }

    for (const [name, ids] of Object.entries(nodeSets)) {
      lines.push(`*NSET, NSET=${name}`);
      for (const id of ids) {
        lines.push(String(id) + ',');
      }
    }

    const normalizedBC = boundaryConditions.map((bc) => {
      if (Array.isArray(bc)) {
        return { line: `${bc[0]}, ${bc[1]}, ${bc[2]}, ${bc[3] || 0}` };
      }
      const dofStart = Array.isArray(bc.dofs) ? bc.dofs[0] : bc.dofStart;
      const dofEnd = Array.isArray(bc.dofs) ? bc.dofs[1] : bc.dofEnd !== undefined ? bc.dofEnd : dofStart;
      if (!Object.prototype.hasOwnProperty.call(nodeSets, bc.set)) {
        throw new Error(`boundary condition references unknown node set "${bc.set}"`);
      }
      return { line: `${bc.set}, ${dofStart}, ${dofEnd}, ${bc.value === undefined ? 0 : bc.value}` };
    });
    if (normalizedBC.length > 0) {
      lines.push('*BOUNDARY');
      for (const bc of normalizedBC) {
        lines.push(bc.line);
      }
    }

    lines.push(isNonLinearGeom ? '*STEP, NLGEOM' : '*STEP', `*${stepType}`);

    if (stepType === 'STATIC') {
      lines.push('0.1, 1.0, 1e-5, 0.2');
    } else {
      lines.push('1e-4, 0.05');
    }

    const normalizedLoads = appliedLoads.map((ld) => {
      if (Array.isArray(ld)) {
        return { line: `${ld[0]}, ${ld[1]}, ${ld[2]}` };
      }
      if (!Object.prototype.hasOwnProperty.call(nodeSets, ld.set)) {
        throw new Error(`applied load references unknown node set "${ld.set}"`);
      }
      return { line: `${ld.set}, ${ld.dof}, ${ld.magnitude}` };
    });
    if (normalizedLoads.length > 0) {
      lines.push('*CLOAD');
      for (const ld of normalizedLoads) {
        lines.push(ld.line);
      }
    }

    lines.push('*NODE FILE', 'U, RF', '*EL FILE', 'S, E, PEEQ', '*END STEP');

    return lines.join('\n');
  }

  /**
   * Returns parsed section contents for verification: { nodes, elements,
   * elementType, elastic, plastic, boundary, cload, step }.
   */
  static parseDeck(deckText) {
    const lines = String(deckText).split('\n');
    const result = {
      nodes: [],
      elements: [],
      elementType: null,
      elastic: null,
      plastic: null,
      density: null,
      boundary: [],
      cload: [],
      step: null,
      hasEndStep: false,
      nodeSets: {}
    };
    let section = null;
    let currentSet = null;

    const isNodeSection = (l) => l.startsWith('*NODE') && !l.startsWith('*NODE FILE');
    for (const raw of lines) {
      const line = raw.trim();
      if (line === '' || line.startsWith('**')) continue;

      if (line.startsWith('*ELEMENT')) {
        const m = line.match(/TYPE=([A-Za-z0-9]+)/);
        result.elementType = m ? m[1] : null;
        section = 'element';
        continue;
      }
      if (line.startsWith('*MATERIAL')) {
        section = 'material';
        continue;
      }
      if (line === '*ELASTIC') {
        section = 'elastic';
        continue;
      }
      if (line === '*DENSITY') {
        section = 'density';
        continue;
      }
      if (line === '*PLASTIC') {
        section = 'plastic';
        continue;
      }
      if (line === '*BOUNDARY') {
        section = 'boundary';
        continue;
      }
      if (line === '*CLOAD') {
        section = 'cload';
        continue;
      }
      if (line.startsWith('*STEP')) {
        result.step = line;
        section = 'step';
        continue;
      }
      if (line.startsWith('*END STEP')) {
        result.hasEndStep = true;
        section = null;
        continue;
      }
      if (line.startsWith('*NSET')) {
        const m = line.match(/NSET=(\S+)/);
        currentSet = m ? m[1] : null;
        if (currentSet && !result.nodeSets[currentSet]) result.nodeSets[currentSet] = [];
        section = 'nset';
        continue;
      }
      if (line === '*NODE') {
        section = 'node';
        continue;
      }
      if (line.startsWith('*')) {
        section = null;
        continue;
      }

      if (section === 'node') result.nodes.push(line);
      else if (section === 'element') result.elements.push(line);
      else if (section === 'elastic') result.elastic = line;
      else if (section === 'density') result.density = line;
      else if (section === 'plastic') result.plastic = result.plastic || line;
      else if (section === 'boundary') result.boundary.push(line);
      else if (section === 'cload') result.cload.push(line);
      else if (section === 'nset' && currentSet) result.nodeSets[currentSet].push(line.replace(/,+$/, ''));
    }
    return result;
  }
}

module.exports = {
  CalculixCaseGenerator,
  VALID_ELEMENT_TYPES
};
